import assert from "node:assert/strict";
import { test } from "node:test";

import {
  AckStatus, Mode, Opcode, decodeAck, decodeHousekeeping, decodeTelecommand,
  encodeAck, encodeHousekeeping, encodeTelecommand,
} from "../../docs/js/messages.js";
import { Apid, PacketError, PacketType, crc16ccitt, decodePacket, encodePacket, toHex } from "../../docs/js/packets.js";

const bytes = (...b) => Uint8Array.from(b);

test("CRC-16/CCITT-FALSE check value", () => {
  assert.equal(crc16ccitt(new TextEncoder().encode("123456789")), 0x29b1);
});

test("packet round trip", () => {
  const original = { packetType: PacketType.TELECOMMAND, apid: Apid.COMMAND, sequenceCount: 1234, payload: bytes(1, 2, 3) };
  assert.deepEqual(decodePacket(encodePacket(original)), original);
});

test("sequence count wraps at 14 bits", () => {
  const packet = { packetType: PacketType.TELEMETRY, apid: Apid.HOUSEKEEPING, sequenceCount: 0x4001, payload: bytes(0x78) };
  assert.equal(decodePacket(encodePacket(packet)).sequenceCount, 1);
});

test("corrupted byte fails CRC", () => {
  const data = encodePacket({ packetType: PacketType.TELEMETRY, apid: Apid.HOUSEKEEPING, sequenceCount: 7, payload: bytes(1, 2, 3, 4, 5) });
  data[7] ^= 0xff;
  assert.throws(() => decodePacket(data), PacketError);
});

test("truncated packet rejected", () => {
  const data = encodePacket({ packetType: PacketType.TELEMETRY, apid: Apid.HOUSEKEEPING, sequenceCount: 7, payload: bytes(1, 2, 3) });
  assert.throws(() => decodePacket(data.slice(0, -1)), PacketError);
});

test("APID out of range", () => {
  assert.throws(() => encodePacket({ packetType: PacketType.TELEMETRY, apid: 0x800, sequenceCount: 0, payload: bytes() }), PacketError);
});

test("telecommand round trip and unknown opcode", () => {
  const tc = { opcode: Opcode.SET_MODE, argument: 2.0 };
  assert.deepEqual(decodeTelecommand(encodeTelecommand(tc)), tc);
  assert.throws(() => decodeTelecommand(bytes(0x63, 0, 0, 0, 0)), PacketError);
});

test("ack round trip", () => {
  const ack = { commandSequence: 42, status: AckStatus.REJECTED, reason: "battery too low" };
  assert.deepEqual(decodeAck(encodeAck(ack)), ack);
});

// Values are exact in 32-bit floats, which the wire format uses for everything but mission time.
const HK = {
  missionTimeS: 1234.5, batterySocPct: 80.5, batteryVoltageV: 7.9375, temperatureC: 15.25,
  latitudeDeg: 30.5, longitudeDeg: -120.75, sunlit: true, heaterOn: false, mode: Mode.SCIENCE,
  commandsAccepted: 3, commandsRejected: 1,
};

test("housekeeping round trip", () => {
  assert.deepEqual(decodeHousekeeping(encodeHousekeeping(HK)), HK);
});

// Golden vectors generated by the Python reference implementation (spacesim.packets/messages).
// If these fail, the JavaScript port is no longer wire-compatible with Python (and the Java/C ports).
test("wire compatibility with Python: housekeeping packet", () => {
  const packet = encodePacket({ packetType: PacketType.TELEMETRY, apid: Apid.HOUSEKEEPING, sequenceCount: 5, payload: encodeHousekeeping(HK) });
  assert.equal(
    toHex(packet),
    "0064c005002440934a000000000042a1000040fe00004174000041f40000c2f180000100020003000146eb",
  );
});

test("wire compatibility with Python: telecommand packet", () => {
  const packet = encodePacket({
    packetType: PacketType.TELECOMMAND, apid: Apid.COMMAND, sequenceCount: 9,
    payload: encodeTelecommand({ opcode: Opcode.SET_MODE, argument: 2.0 }),
  });
  assert.equal(toHex(packet), "10c8c00900060140000000ad19");
});

test("wire compatibility with Python: ack packet", () => {
  const packet = encodePacket({
    packetType: PacketType.TELEMETRY, apid: Apid.COMMAND_ACK, sequenceCount: 9,
    payload: encodeAck({ commandSequence: 9, status: AckStatus.REJECTED, reason: "unknown mode 7" }),
  });
  assert.equal(toHex(packet), "00c9c0090012000901756e6b6e6f776e206d6f646520378b46");
});
